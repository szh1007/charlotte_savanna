# 拉取历史聊天记录的条数
QUERY_HISTORY_LIMIT = 10

# 主体名称阈值 - 确认/候选
# 如何设置: 根据项目环境, 使用大量名称测试集, 测试上限范围和候选范围
# 影响因素: 环境配置 / 是否归一化 / 相似度比较 / 排名器 / 权重比
ITEM_NAME_CONFIRM_THRESHOLD = 0.70
ITEM_NAME_CANDIDATE_THRESHOLD = 0.60
# 「问题里没点名主体」时的内容兜底阈值.
#
# 真实用户不会总说全称 —— 问「网络日志留存多久」时他指的是《网络安全法》, 但句子里
# 没有这个名字. 这时改走内容兜底: 先在全库 chunk 上召回, 看命中的块属于哪份文档.
# 门槛比主体名确认那条低 (0.70), 因为两条路的分数分布不同 —— 实测过一轮:
#   0.70 -> 只有 50% 的题被接住, 但接住的都对
#   0.65 -> 86% 的题被接住, 14% 会把问题分给一份相近的文档 (多半是两份文档写了
#           同一条规则, 比如「处理不满十四周岁未成年人信息要取得监护人同意」)
# 取 0.65: 宁可偶尔分错文档 (检索仍会按内容排序, 相邻文档的块排后面), 也别把大
# 半口语化提问直接挡在检索门外.
ITEM_NAME_CONTENT_FALLBACK_THRESHOLD = 0.65

# 主体名称确认/候选的选择数量
# 可以在前端给用户展示候选项
ITEM_NAME_CONFIRM_TOPK = 1
ITEM_NAME_CANDIDATE_TOPK = 2

# 每一路召回(向量 / HyDE)各自取回的候选数量.
# 这个池子决定 recall 的上限, 后面的精排再准也捞不回来.
MILVUS_CHUNK_RECALL_TOP_K = 10

# RRF 融合后保留多少条进精排.
# 「召回 多 -> 精排 少」才是有腾挪空间的漏斗; 此前召回/融合/精排共用 5,
# 精排只能在 5 条里挑 3 条, 等于白排.
MILVUS_CHUNK_RRF_TOP_K = 10

# 精排后交给作答节点的条数**上限**.
#
# 2026-10-06 (C17) 由 8 改成 1 —— 依评测扫参的结果, 不是拍的:
#   交付 1 条: 精确 0.922 / 召回 0.870
#   交付 2 条: 精确 0.507 / 召回 0.916   (第 2 条是答案的概率只有约 1/3)
#   交付 3 条: 精确 0.342 / 召回 0.928
# 多带一条只多换回约 5 个点的召回, 却把精确率砍掉一半 —— 法条问答的答案基本落在
# 单条条文里, 所以把交付收窄到 1 条. 取 1 之后断崖 (下面那组 GAP 参数) **不再参与**
# (上限等于下限, 直接取前 N 条); 判据与参数留着 —— 哪天要把交付放宽 (比如作答需要
# 更多上下文), 它仍是决定"放宽到几条"的机制.
#
# 旧注释 (默认 8 时的口径) 留着: **返回几条由断崖决定, 不由这里卡死** —— 分数一路平滑、
# 找不到掉队位置时就全给; 有明显掉队的位置就在那里断开. 这个数只兜住极端情况
# (比如 8 条彼此接近却都不相关).
# 注意它同时是 precision 的分母(命中数/K) 和 recall 的分子上限, 所以调大调小
# 只是换刻度 —— 读 precision 时先看这一层返回了几条.
RERANK_MAX_TOPK: int = 1

# 断崖截断的下限: 从这里之后才开始找断崖点, 它之前的一律保留.
#
# 这个值**不能**等于 RERANK_MAX_TOPK —— 断崖检测是从下限处才开始向后看的,
# 两者相等等于「前 N 条无条件保留, 它们中间有断崖也看不见」: 实测 8 条候选里
# 分数从 0.95 掉到 0.05 (跨度 0.9), 仍然原样返回 8 条. 判据改成「相对头部的
# 累计衰减」之后已经比相邻判据稳健得多, 下限只需兜住极端情形.
RERANK_MIN_TOPK: int = 1

# 精排开关.
# 关掉时跳过打分, 直接按 RRF 顺序截取 RERANK_MAX_TOPK 条.
# 保留开关而不是直接删掉, 是为了分块质量改善后重测一轮, 确认结论是否改变.
ENABLE_RERANK: bool = True

# RRF 分数与精排分数的融合权重.
# 只按精排分数排等于「一票否决」—— reranker 打偏时没有任何兜底, 而它在中文长
# 融合之后精排仍能把明显更相关的顶上来, 万一打偏 RRF 的先验也能拽回一部分.
# 取 0 = 纯精排 (旧行为), 取 1 = 纯 RRF 顺序.
RERANK_FUSION_ALPHA: float = 0.0

# 「文档标题片」的融合分折扣.
#
# 标题片 = 文档开头那一块 (`# 项目名` + 项目简介). 它含项目名、又通篇讲这个
# 项目, 与任何带主体名的问题字面重合度都最高 —— 实测 40 题里 35 题它都进了
# 候选池, 而它真正是答案的只有 2 题 (「XX 是什么项目」那种).
#
# **不排除它** (那 2 题要它), 只在融合分上打折, 让它别挤掉具体的章节块.
# 取 1.0 = 不干预.
#
# 2026-10-06 (C17) 由 0.7 改回 1.0: 0.7 是**上一版语料** (4 份项目说明文档) 上扫出来的.
# 换成 15 篇法规之后重扫, 打折反而有害 —— 同一套题下:
#   打折 0.7 -> 精确 0.870 / 召回 0.818
#   不打折   -> 精确 0.922 / 召回 0.870
# 旧语料是项目 README, 开头的「项目简介」块确实爱抢名次; 法规文件的开头是标题与
# 通过日期, 没有那个问题 —— 参数跟着语料走, 换了语料就得重扫.
DOC_HEAD_SCORE_FACTOR: float = 1.0

# 检查断崖的参数: 每个位置的分数与**第 1 名**比的累计衰减门槛.
# 跌破 `head - ABS` 或 `head * (1 - RATIO)` 就在该处断开.
# 注意是「相对头部」而不是「相邻两点」—— 0.8 / 0.7 / 0.6 / 0.5 这种缓慢下滑,
# 相邻两点每步只差 0.1, 永远触发不了, 可到第 3 个已经比头部低 25% 了.
RERANK_GAP_RATIO: float = 0.2
RERANK_GAP_ABS: float = 0.2
# Reranker 的上下文窗口上限 (token).
# 超过它的候选**不做任何加工** —— 直接交给模型按窗口截断 (截断是确定的,
# LLM 压缩不是). 必须与 `RK_BGE_RERANKER_MAX_LENGTH` 和 `RERANK_LENGTH_TIERS[-1]`
# 对齐, 否则会出现「压到 A 却被模型按 B 截掉」这种两头不讨好的情况.
RERANK_MAX_INPUT_TOKENS: int = 2048

# 精排窗口的**档位** (token): 按本批候选里最长的那一条向上取档.
# 窗口决定 padding 宽度, 而 reranker 的 attention 是平方复杂度 —— 一批文本最长
# 只有 900 token 时用 1024 跑, 比一律按 2048 快好几倍; 真出现长文本才升档.
RERANK_LENGTH_TIERS: tuple[int, ...] = (1024, 2048)
