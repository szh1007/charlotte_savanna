"""工具层的全局配置: 只有一项 —— 工具调用的缺省超时 (#15).

一句话理解: 工具卡住不返回时, 框架最多等多久. 每个工具都能用
`@tool(timeout=...)` 覆盖它; 没写 `timeout` 的工具取这里的值.

**30 秒怎么来的** (不是手感, 是分层里那一段的位置, DESIGN §② #15):

| 层 | 值 | 在哪 |
|----|----|------|
| 工具 | 10-30 秒 | 本文件 (每工具可覆盖) |
| 模型 | 60 秒 | `model/client_httpx.py` 的构造参数 |
| run | 90 秒 | 业务配的 `agent/guard.py` 的 max_duration_seconds |

取那一段的**上界**, 理由是给「工具自带的超时」让路: 一个自己会设限的工具
(典型形态是经一个带超时的 HTTP client 出门) 总比框架先响, 而它给的话更准
(哪个下游慢 / 什么错). 框架这一层是**兜底**, 只管那些自己不设限的工具 (裸查库 /
裸读文件); 兜底值又必须明显小于模型层与 run 层, 否则一次卡住的工具会把整轮的
时间预算吃光 —— 而「整轮不结束」正是这一片要堵的洞.

**不提供「不设超时」这个选项**: 想要更慢就跑完, 给一个更大的数 (它仍然受 run
预算约束); 而「永不超时」本身就是那个洞.
"""

from __future__ import annotations

# 工具调用的缺省超时秒数 (单个工具可用 @tool(timeout=...) 覆盖)
DEFAULT_TOOL_TIMEOUT_SECONDS = 30.0
